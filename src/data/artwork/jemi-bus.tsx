export function JemiBusLogo({
  ink = INK,
  paper = PAPER,
  ...props
}: SVGProps<SVGGElement> & { ink?: string; paper?: string }) {
  const cutId = useId();
  const transparent = paper === 'none';
  return (
    <g {...props}>
      <g transform="rotate(-6,110,110)" strokeLinejoin="round">
        {transparent && (
          // khoét mặt chữ khỏi phần mực
          <mask id={cutId} maskUnits="userSpaceOnUse" x="-100" y="-100" width="500" height="500">
            <rect x="-100" y="-100" width="500" height="500" fill="#FFFFFF" />
            <g fill="#000000" stroke="#000000" strokeWidth={FAT}>{BODY}</g>
          </mask>
        )}
        <g mask={transparent ? `url(#${cutId})` : undefined}>
          {/* khối đổ bóng */}
          <g transform="translate(4,13)" fill={ink} stroke={ink} strokeWidth={22 + FAT}>{BODY}</g>
          {/* lấp khe giữa các chữ để viền liền một khối */}
          <g transform="translate(2,6.5)" fill={ink} stroke={ink} strokeWidth={30 + FAT}>{BODY}</g>
          {/* viền */}
          <g fill={ink} stroke={ink} strokeWidth={22 + FAT}>{BODY}</g>
        </g>
        {!transparent && (
          <g fill={paper} stroke={paper} strokeWidth={FAT}>
            {BODY}
          </g>
        )}
      </g>
    </g>
  );
}
